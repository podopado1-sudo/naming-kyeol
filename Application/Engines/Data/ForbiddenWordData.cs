    /// <summary>
    /// 금칙어 포함 여부 체크 (부분 일치, Contains 방식)
    /// 이름 또는 성+이름 전체 문자열에 금칙어가 포함되어 있는지 검사
    /// </summary>
    public static bool ContainsForbiddenWord(string text)
    {
        foreach (var word in ForbiddenWords)
        {
            if (text.Contains(word)) return true;
        }
        return false;
    }

    /// <summary>
    /// 생활어 충돌 여부 체크 (완전일치 + 부분 일치)
    /// </summary>
    public static bool IsCollisionWithCommonWord(string name)
    {
        foreach (var word in CollisionWords)
        {
            if (name == word || name.Contains(word) || word.Contains(name))
            {
                return true;
            }
        }
        return false;
    }
