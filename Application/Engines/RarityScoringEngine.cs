    };

    public async Task<int> CalculateRarityScoreAsync(string name)
    {
        if (string.IsNullOrEmpty(name))
            return 0;

        int score = 100; // 기본 점수 (매우 희귀)

        // 1단계: 이름 데이터베이스 직접 매칭
        if (VeryCommonNames.Contains(name))
        {
            score = 10; // 매우 흔함
        }
        else if (CommonNames.Contains(name))
        {
            score = 30; // 흔함
        }
        // 2단계: 구세대 돌림자 패턴 체크
        else if (HasOldStyleEnding(name))
        {
            score = 50; // 구세대 패턴
        }
        // 3단계: 현세대 흔한 끝글자 패턴 체크 (약한 감점)
        else if (HasModernCommonEnding(name))
        {
            score = 65; // 현세대 흔한 패턴이지만 DB에 없으므로 중상
        }
        // 4단계: 길이/독창성 보너스
        else
        {
            // 4음절 이상은 매우 희귀
            if (name.Length >= 4)
            {
                score = 100;
            }
            // 3음절은 약간 희귀
            else if (name.Length >= 3)
            {
                score = 90;
            }
            // 특이한 초성 조합이면 최고 보너스
            else if (HasUniqueCombination(name))
            {
                score = 95;
            }
            // 2음절이면서 DB(500개+)에 없는 이름 → 충분히 희귀
            else
            {
                score = 90;
            }
        }

        return await Task.FromResult(Math.Max(0, Math.Min(100, score)));
    }

    /// <summary>
    /// 구세대 돌림자 패턴 체크 (길, 복, 남, 숙, 순, 자, 영, 옥, 희, 미 등)
    /// </summary>
    private bool HasOldStyleEnding(string name)
    {
        if (name.Length < 2)
            return false;

        var lastChar = name[^1].ToString();
        return CommonEndingsOld.Contains(lastChar);
    }

    /// <summary>
    /// 현세대 흔한 끝글자 패턴 체크 (준, 우, 현, 서, 윤, 은 등)
    /// DB에 직접 매칭되지 않았지만 흔한 끝글자를 가진 이름
    /// </summary>
    private bool HasModernCommonEnding(string name)
    {
        if (name.Length < 2)
            return false;

        var lastChar = name[^1].ToString();
        return CommonEndingsModern.Contains(lastChar);
    }

    /// <summary>
    /// 특이한 초성 조합인지 확인
    /// KoreanUtils로 실제 초성 추출하여 판단
    /// ㅊ, ㅋ, ㅌ, ㅍ, 쌍자음 등이 포함되면 독특한 이름
    /// </summary>
    private bool HasUniqueCombination(string name)
    {
        if (name.Length < 2)
            return false;

        int uniqueCount = 0;

        foreach (char c in name)
        {
            var (initial, _, _) = KoreanUtils.Decompose(c);
            if (string.IsNullOrEmpty(initial))
                continue;

            if (UniqueInitials.Contains(initial))
                uniqueCount++;
        }

        // 특이한 초성이 1개 이상이면 독특한 조합
        return uniqueCount >= 1;
    }
