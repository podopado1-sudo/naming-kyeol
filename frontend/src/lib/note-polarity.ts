/**
 * 평가 노트 극성 — 감점·주의·참고 성격의 노트를 가른다. EvalPrimitives NotesList가 좋은 점은 청록 ✓,
 * 이 함수가 true인 노트는 중립 막대로 그린다. 모든 노트에 청록 ✓를 붙여 '유행 이름 감점'·'(감점)'·
 * '대흉'까지 좋은 점처럼 보이던 것을 가른다(감사 UX-3·EV-4). React 없이 node --test로 검사하려고
 * 컴포넌트 파일에서 뺐다(tests/note-polarity.test.mjs).
 *
 * 백엔드 노트 문구(AestheticEngine·HarmonyEngine Notes.Add)를 기준으로 한 키워드다.
 * - '부족한 오행 보완'처럼 긍정 문장에 '부족'이 들어가므로 '부족'은 '정보 부족' 꼴만 잡는다.
 * - '동음'(부정 연상 단어와 동음, 감점 10)은 2026-10-21 검토에서 ✓로 남던 것을 추가.
 * - 획수 조화 20 의 감산 노트 '일부 한자 획수 정보 부족 — 획수 조화 신뢰도 감산'은 '정보 부족'·'감산'이 잡는다.
 *   옛 노트 두 가지에만 쓰던 '미검수'·'보수적'·'신뢰도가? 낮'은 2026-10-26 뺐다 — '획수 자료 미검수 글자 포함 — 획수 조화
 *   점수 보수적 산출'은 B3(Core 아니면 ×0.85 폐기)로, '일부 한자의 오행 판정 신뢰도가 낮음 — 자원오행 점수 보수적 산출'은
 *   S4(2026-10-22)로 백엔드에서 없어졌고 두 배포 모두 나갔다. 노트는 /evaluate 응답에서 바로 그리고 저장하지 않으므로
 *   (즐겨찾기는 점수만 저장) 옛 문구가 다시 뜰 길이 없다.
 * - '감점 일부 상쇄'(기신이 부족한 오행이라 +10)는 가점이라 ✓로 둔다 — '감점' 뒤 부정 전방탐색.
 * - '발음오행: A→B→C'(HarmonyEngine 발음오행 — 전체 상생이 아닐 때의 분기)는 상극이 섞일 수 있어
 *   중립으로 둔다(2026-10-21 검토 FTE-8: 김서준 '발음오행: 木→金→金'이 ✓였다 — 金克木).
 *   전체 상생일 때의 '발음오행 전체 상생: …'은 콜론 앞에 말이 더 있어 걸리지 않고 ✓로 남는다
 * - 수리 노트는 모두 중립이다 — 4격 요약은 '참고'(등급 말 '피하는 수'도 '피하'), 획수를 자동으로 고른 한자로 셌다는 안내는 '추정'
 * 근본 해결은 백엔드가 노트마다 극성을 담아 보내는 것(키워드 추측 대신).
 */

/**
 * 지금 백엔드 노트 문구에 실제로 나오는 감점·주의 표지(정규식 조각). tests/note-polarity.test.mjs 가 각 조각이
 * AestheticEngine.cs·HarmonyEngine.cs 의 문자열 리터럴에 아직 있는지 대조한다 — 백엔드가 문구를 지우면
 * 여기서도 빼야 테스트가 지나간다('미검수'가 B3 뒤에도 남아 있던 것).
 */
export const CAUTION_NOTE_PATTERNS = [
  "^발음오행:",
  "감점(?! 일부 상쇄)",
  "충돌",
  "맞지 않",
  "불일치",
  "편중",
  "정보가? 부족",
  "생략",
  "추정",
  "참고",
  "피하",
  "기본값",
  "세대 감각",
  "동음",
  "감산",
] as const;

/**
 * 지금 노트 문구에는 없지만 새 노트가 생길 때를 대비해 두는 일반 주의어. '흉'은 옛 수리 등급 말('대흉' — 지금은 '피하는 수').
 * 백엔드 문구가 이 말을 다시 쓰면 위 목록으로 옮긴다(테스트가 알려 준다).
 */
export const GENERIC_CAUTION_PATTERNS = ["흉", "주의", "상극"] as const;

const CAUTION_NOTE_RE = new RegExp(
  [...CAUTION_NOTE_PATTERNS, ...GENERIC_CAUTION_PATTERNS].join("|")
);

export function isCautionNote(text: string): boolean {
  return CAUTION_NOTE_RE.test(text.trim());
}
