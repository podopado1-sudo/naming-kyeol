    [Fact]
    public void A197_AllForbidden_NoneWeak()
    {
        Assert.Equal(197, A197.Distinct().Count());
        foreach (var cp in A197)
        {
            Assert.True(HanjaData.IsForbiddenNameHanja(Cp(cp)), $"U+{cp:X4} 불용이어야 한다");
            Assert.False(HanjaData.IsWeakGivenNameHanja(Cp(cp)), $"U+{cp:X4} 약자 세트와 겹친다");
        }
    }

    /// <summary>약자였던 넷(娭·咢·媢·螞)은 약자 세트에서 옮겼다 — 불용·약자 두 세트는 겹치지 않는다(사전 전체로 확인).</summary>
    [Fact]
    public void ForbiddenAndWeakSets_DoNotOverlap()
    {
        foreach (var cp in new[] { 0x5A2D, 0x54A2, 0x5AA2, 0x879E })
            Assert.Contains(cp, A197);
        var both = HanjaData.GetAllHanja()
            .Where(h => HanjaData.IsForbiddenNameHanja(h.Character) && HanjaData.IsWeakGivenNameHanja(h.Character))
            .Select(h => h.Character).ToList();
        Assert.Empty(both);
    }
